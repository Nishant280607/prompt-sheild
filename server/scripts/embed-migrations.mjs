#!/usr/bin/env node
/**
 * Embeds every prisma/migrations/<name>/migration.sql into src/generated/migrations.ts.
 *
 * The server applies these at start-up (src/db/migrate.ts). That makes a fresh database work
 * without a separate CLI step - needed on serverless hosts such as Vercel, which bundle only
 * the code the server imports. Runs automatically on install, `db:generate`, `db:migrate`
 * and `build`; src/generated/ is git-ignored like the generated Prisma client.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const serverRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = path.join(serverRoot, 'prisma', 'migrations');
const outFile = path.join(serverRoot, 'src', 'generated', 'migrations.ts');

const migrations = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && /^\d+_/.test(entry.name))
  .map((entry) => entry.name)
  .filter((name) => existsSync(path.join(migrationsDir, name, 'migration.sql')))
  .sort()
  .map((name) => {
    const bytes = readFileSync(path.join(migrationsDir, name, 'migration.sql'));
    // Same checksum Prisma Migrate stores in _prisma_migrations (SHA-256 of the script).
    return {
      name,
      checksum: createHash('sha256').update(bytes).digest('hex'),
      sql: bytes.toString('utf8'),
    };
  });

const source = `// Generated by scripts/embed-migrations.mjs from prisma/migrations - do not edit.
export interface EmbeddedMigration {
  name: string;
  checksum: string;
  sql: string;
}

export const MIGRATIONS: readonly EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)};
`;

mkdirSync(path.dirname(outFile), { recursive: true });
const previous = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
if (previous !== source) writeFileSync(outFile, source, 'utf8');
console.log(`Embedded ${migrations.length} migration(s) into src/generated/migrations.ts`);
